/**
 * 时刻换算的唯一定义处（核心与转换器共用）。
 *
 * 谱面时间轴统一毫秒精度：转换器写谱面、运行时合成铺底、回放裁剪都落在
 * 同一张时间轴上，同一输入必得同一串数（产物可逐字节对拍）。此前铺底在
 * core/pad.ts 手抄了一份同样的 round，改精度时必然只改一处——收回这里。
 *
 * 纯层：无 DOM / Web Audio 依赖；core 与 converter 都可引用。
 */

/**
 * 秒 → 毫秒圆整（三位小数）。谱面时刻、铺底时刻、伴奏窗口共用一个精度，
 * 保证「同一时刻」在两处算出来是同一个数。
 */
export function roundMs(t: number): number {
  return Math.round(t * 1000) / 1000
}
