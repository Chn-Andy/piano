/**
 * 判定窗口（GLOSSARY：判定；ADR-0013）——**整个游戏的核心手感，唯一定义处**。
 *
 * 判定对象：音符**中心与判定线重合的那一刻**就是该音符的时刻（0 偏差，
 * renderer 的 y = 判定线 − 剩余时间 × 下落速度）。判定量只有一个：
 * |按键时刻 − 音符时刻|，按键时刻取按下那一瞬的音频主时钟（ADR-0010）。
 * 与早/晚方向无关、与连击无关、与谱面密度无关、与音符颜色无关。
 *
 * | 偏移量（含等号）  | 判定      | 伤害系数 | 连击 |
 * |-------------------|-----------|----------|------|
 * | ≤ perfect（50ms） | Perfect 完美 | ×1.0 | +1 |
 * | ≤ good（120ms）   | Good 良好    | ×0.7 | +1 |
 * | > good            | Miss 失误    | 无（扑空） | 归零 |
 *
 * 三条口径（都有测试钉着，见 simulator.test.ts「判定窗口边界」）：
 * 1. **边界含等号**：偏差恰好 50ms 判完美、恰好 120ms 判良好。
 * 2. **一颗音符只判一次**：命中即消费；早于 good 窗的按键**不消耗音符**
 *    （音符继续等着，那次按键只是空按），迟过 good 窗才判失误。
 * 3. **失误由时间判定而非按键判定**：音符等到 good 窗过期才落 Miss。
 *
 * 这三档在屏幕上有多宽（FALL_SPEED 340px/s 折算）：完美带 ±17px、
 * 良好带到 ±41px——都小于一颗音符（26px 高），肉眼分辨不出。所以偏差
 * 必须以**数字**反馈（判定闪示的「早/晚 N」，结算的平均偏差），否则玩家
 * 学不会「老是偏晚 → 去设置里调正音画偏移」（ADR-0013）。
 */
export const JUDGMENT_WINDOWS = {
  /** Perfect 判定半宽：|按键 - 音符| ≤ 此值 → Perfect（边界含） */
  perfect: 0.05,
  /** Good 判定半宽：|按键 - 音符| ≤ 此值 → Good（边界含）；超出不判定，音符等待 Miss */
  good: 0.12,
} as const

export type JudgmentTierName = keyof typeof JUDGMENT_WINDOWS

